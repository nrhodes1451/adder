// Generates src/engine/functions.ts: the built-in function names of the
// installed @ironcalc/wasm. IronCalc has no API listing them, so we take
// candidate words from the WASM binary and keep the ones the engine accepts
// as functions (it upper-cases known names and leaves unknown ones as typed).
// Names for all languages are stored back to back ("MITTELWERTAVERAGE…"),
// so every substring of each run of capitals is a candidate.
// Re-run after upgrading IronCalc: node scripts/gen-functions.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const wasmPath = require.resolve("@ironcalc/wasm/wasm_bg.wasm");
const { default: init, Model } = await import(require.resolve("@ironcalc/wasm/wasm.js"));
const bytes = readFileSync(wasmPath);
await init({ module_or_path: bytes });

const text = bytes.toString("latin1");
const candidates = new Set();
for (const m of text.matchAll(/[A-Z0-9.]{2,}/g)) {
  const run = m[0];
  for (let i = 0; i < run.length; i++) {
    if (!/[A-Z]/.test(run[i])) continue;
    for (let j = i + 2; j <= Math.min(run.length, i + 25); j++) {
      if (run[j - 1] !== ".") candidates.add(run.slice(i, j));
    }
  }
}

const known = [];
const model = new Model("probe", "en", "UTC", "en");
model.pauseEvaluation(); // only parsing matters here
for (const name of candidates) {
  try {
    model.setUserInput(0, 1, 1, `=${name.toLowerCase()}()`);
    if (model.getCellContent(0, 1, 1).startsWith(`=${name}(`)) known.push(name);
  } catch {
    // not a function
  }
}
known.sort();

const version = JSON.parse(readFileSync(require.resolve("@ironcalc/wasm/package.json"), "utf8")).version;
const out = `// Generated by scripts/gen-functions.mjs from @ironcalc/wasm ${version}. Do not edit.
export const BUILTIN_FUNCTIONS: readonly string[] = ${JSON.stringify(known, null, 2)};
`;
writeFileSync(new URL("../src/engine/functions.ts", import.meta.url), out);
console.log(`${known.length} functions (from ${candidates.size} candidates)`);
